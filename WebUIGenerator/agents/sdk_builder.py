def _useapi_hook_source() -> str:
    """The real useApi hook the app runs against (bundled at finalize by _bundle_api_server).
    Seeded early so the agent's pages typecheck against it during the build."""
    tmpl = Path(__file__).parent / "services_engineer" / "templates" / "useApi.hook.ts"
    try:
        return tmpl.read_text(encoding="utf-8")
    except Exception:
        return "export function useApi<T=any>(_t: string): { data: T[]; loading: boolean; error: string|null } {\n  return { data: [], loading: false, error: null };\n}\nexport function apiAggregate(..._a: any[]): any { return null; }\n"


def _slugify(name: str) -> str:
    return re.sub(r"[^a-z0-9-]", "-", (name or "app").lower()).strip("-") or "app"


