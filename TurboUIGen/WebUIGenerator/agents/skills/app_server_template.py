@app.get("/api/data/{table}/aggregate")
async def get_table_aggregate(
    table: str,
    groupBy: str | None = None,
    metric: str = Query("count", regex="^(sum|avg|min|max|count)$"),
    column: str | None = None,
    filter: str | None = None,
    limit: int = Query(50, ge=1, le=200),
):
    tables = _get_tables()
    if table not in tables:
        raise HTTPException(status_code=404, detail=f"Table '{table}' not found")

    where_clause = ""
    params: list = []
    if filter:
        filters = filter.split(";")
        conditions = []
        for f in filters:
            clause, vals = _parse_filter(f)
            if clause:
                conditions.append(clause)
                params.extend(vals)
        if conditions:
            where_clause = "WHERE " + " AND ".join(conditions)

    if metric == "count":
        agg_expr = "COUNT(*)"
    else:
        if not column:
            raise HTTPException(status_code=400, detail=f"'column' required for metric '{metric}'")
        col_safe = re.sub(r"[^a-zA-Z0-9_]", "", column)
        agg_expr = f"{metric.upper()}([{col_safe}])"

    conn = _get_db()
    if groupBy:
        group_safe = re.sub(r"[^a-zA-Z0-9_]", "", groupBy)
        query = f"SELECT [{group_safe}] as _group, {agg_expr} as _value FROM [{table}] {where_clause} GROUP BY [{group_safe}] ORDER BY _value DESC LIMIT ?"
        rows = conn.execute(query, params + [limit]).fetchall()
        conn.close()
        return {"data": [{"group": r["_group"], "value": r["_value"]} for r in rows]}
    else:
        query = f"SELECT {agg_expr} as _value FROM [{table}] {where_clause}"
        row = conn.execute(query, params).fetchone()
        conn.close()
        return {"value": row["_value"]}


