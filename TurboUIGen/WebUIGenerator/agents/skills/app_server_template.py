def _parse_llm_response(text: str) -> dict[str, Any]:
    """Parse LLM response for embedded chart/table/map blocks."""
    map_match = re.search(r"```map\s*\n([\s\S]*?)\n```", text)
    if map_match:
        try:
            data = json.loads(map_match.group(1))
            clean = text[:map_match.start()].strip() + "\n\n" + text[map_match.end():].strip()
            return {"response": clean.strip(), "type": "map", "data": data}
        except json.JSONDecodeError:
            pass

    chart_match = re.search(r"```chart\s*\n([\s\S]*?)\n```", text)
    if chart_match:
        try:
            data = json.loads(chart_match.group(1))
            clean = text[:chart_match.start()].strip() + "\n\n" + text[chart_match.end():].strip()
            return {"response": clean.strip(), "type": "chart", "data": data}
        except json.JSONDecodeError:
            pass

    table_match = re.search(r"```table\s*\n([\s\S]*?)\n```", text)
    if table_match:
        try:
            data = json.loads(table_match.group(1))
            clean = text[:table_match.start()].strip() + "\n\n" + text[table_match.end():].strip()
            return {"response": clean.strip(), "type": "table", "data": data}
        except json.JSONDecodeError:
            pass

    try:
        data = json.loads(text)
        if isinstance(data, dict) and "type" in data:
            return {"response": text, "type": "chart", "data": data}
        if isinstance(data, list):
            return {"response": text, "type": "table", "data": data}
    except json.JSONDecodeError:
        pass

    return {"response": text, "type": "text", "data": None}


@app.post("/api/chat")
async def chat(request: ChatRequest):
    import asyncio
    from openai import AsyncOpenAI
    global llm_client, http_client

    if not llm_client:
        raise HTTPException(status_code=503, detail="LLM not configured — check .env credentials")

    try:
        system_prompt = _build_chat_system_prompt()
        if request.context:
            system_prompt += f"\n\nAdditional context: {json.dumps(request.context)}"

        if request.responseFormat == "chart":
            system_prompt += "\n\nIMPORTANT: Respond with a chart visualization using the ```chart format."
        elif request.responseFormat == "table":
            system_prompt += "\n\nIMPORTANT: Respond with tabular data using the ```table format."

        # Inject sample data into system prompt for accurate answers
        sample_data = {}
        conn = _get_db()
        for meta in _api_metadata[:5]:
            rows = conn.execute(f"SELECT * FROM [{meta['table']}] LIMIT 10").fetchall()
            sample_data[meta["table"]] = [dict(r) for r in rows]
        conn.close()
        system_prompt += f"\n\n## Sample data (first 10 rows per table)\n```json\n{json.dumps(sample_data, default=str, indent=2)}\n```"

        messages = [{"role": "system", "content": system_prompt}]
        # Keep only last 20 messages to avoid exceeding token limits
        recent = request.messages[-20:] if len(request.messages) > 20 else request.messages
        messages.extend([{"role": m.role, "content": m.content} for m in recent])

        last_err = None
        for _attempt in range(3):
            try:
                completion = await llm_client.chat.completions.create(
                    model=LITELLM_MODEL,
                    messages=messages,
                    temperature=0.3,
                )
                text = completion.choices[0].message.content
                return _parse_llm_response(text)
            except Exception as attempt_err:
                last_err = attempt_err
                print(f"[chat] attempt {_attempt+1} failed: {type(attempt_err).__name__}: {attempt_err}", flush=True)
                if _attempt < 2:
                    # Recreate HTTP client on connection errors (stale pool, SSL tear-down)
                    try:
                        await http_client.aclose()
                    except Exception:
                        pass
                    http_client = _make_http_client()
                    llm_client = AsyncOpenAI(
                        api_key=LITELLM_API_KEY,
                        base_url=LITELLM_API_BASE.rstrip("/") + "/v1",
                        http_client=http_client,
                        timeout=LITELLM_TIMEOUT,
                    )
                    await asyncio.sleep(2 * (_attempt + 1))
        raise HTTPException(status_code=500, detail=f"LLM call failed after 3 attempts: {last_err}")
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))


