# --- Generic Data Endpoints ---
def _parse_filter(filter_str: str) -> tuple[str, list]:
    """Parse 'column:operator:value' into SQL WHERE clause."""
    parts = filter_str.split(":", 2)
    if len(parts) != 3:
        return "", []
    col, op, val = parts
    col_safe = re.sub(r"[^a-zA-Z0-9_]", "", col)
    ops = {"eq": "=", "ne": "!=", "gt": ">", "lt": "<", "gte": ">=", "lte": "<=", "like": "LIKE"}
    if op == "in":
        values = val.split(",")
        placeholders = ",".join("?" * len(values))
        return f"[{col_safe}] IN ({placeholders})", values
    if op not in ops:
        return "", []
    sql_op = ops[op]
    if op == "like":
        val = f"%{val}%"
    return f"[{col_safe}] {sql_op} ?", [val]


@app.get("/api/data/{table}")
async def get_table_data(
    table: str,
    limit: int = Query(100, ge=1, le=1000),
    offset: int = Query(0, ge=0),
    sort: str | None = None,
    order: str = Query("asc", regex="^(asc|desc)$"),
    filter: str | None = None,
):
    tables = _get_tables()
    if table not in tables:
        raise HTTPException(status_code=404, detail=f"Table '{table}' not found")

    conn = _get_db()
    where_clause = ""
    params: list = []

    if filter:
        filters = filter.split(";")
        conditions = []
        for f in filters:
            clause, vals = _parse_filter(f)
            if clause:
                conditions.append(clause)
                params.extend(vals)
        if conditions:
            where_clause = "WHERE " + " AND ".join(conditions)

    count_sql = f"SELECT COUNT(*) as c FROM [{table}] {where_clause}"
    total = conn.execute(count_sql, params).fetchone()["c"]

    sort_clause = ""
    if sort:
        sort_safe = re.sub(r"[^a-zA-Z0-9_]", "", sort)
        sort_clause = f"ORDER BY [{sort_safe}] {order.upper()}"

    query = f"SELECT * FROM [{table}] {where_clause} {sort_clause} LIMIT ? OFFSET ?"
    rows = conn.execute(query, params + [limit, offset]).fetchall()
    conn.close()

    data = [dict(r) for r in rows]
    return {
        "data": data,
        "total": total,
        "limit": limit,
        "offset": offset,
        "hasMore": (offset + limit) < total,
    }


