        "  - Use mapType \"usa\" only if data has US state-level granularity (id = state FIPS or postal code)\n"
        "  - Use a map when the user asks to \"show on a map\", \"visualize geographically\", or when the data has a clear geographic dimension and the user asks for a spatial view\n"
        "- If best as a table, wrap it in ```table\\n[{...}, ...]\\n```\n"
        "- Otherwise respond in plain text with markdown formatting.\n"
        "- Use the actual data from the database to compute your answers.\n"
        "- When asked to show data, query it and include real values — never make up numbers.\n"
