# ── Naming helpers ────────────────────────────────────────────────────────────

def _singularize(name: str) -> str:
    if name.endswith("ies"):
        return name[:-3] + "y"
    if name.endswith("s") and not name.endswith("ss"):
        return name[:-1]
    return name


def _tool_name_from_endpoint(ep: dict) -> str:
    segs = [s for s in ep["path"].split("/") if s]
    if segs and segs[-1].startswith("{"):
        resource = _singularize(segs[-2]) if len(segs) >= 2 else "item"
        name = f"get_{resource}_by_{segs[-1].strip('{}')}"
    else:
        resource = segs[-1] if segs else "root"
        name = f"list_{resource}"
    return re.sub(r"[^a-z0-9_]", "_", name.lower()).strip("_") or "tool"


def _split_params(parameters: list[dict], path: str) -> tuple[list[str], list[dict]]:
    path_param_names = re.findall(r"\{(\w+)\}", path)
    query_params = [p for p in parameters if p.get("in") == "query" and p.get("name")]
    return path_param_names, query_params


def _py_type(openapi_type: str | None) -> str:
    return {"integer": "int", "number": "float", "boolean": "bool"}.get(openapi_type, "str")


def _dedupe_params(params: list[dict]) -> list[dict]:
    """First-occurrence-wins dedup by name — a custom tool's SQL may
    legitimately reference the same named parameter at more than one `?`
    placeholder, which is fine in the SQL/binding tuple but would be a
    duplicate-argument SyntaxError in a generated Python function signature."""
    seen = set()
    out = []
    for p in params:
        if p["name"] not in seen:
            out.append(p)
            seen.add(p["name"])
    return out
