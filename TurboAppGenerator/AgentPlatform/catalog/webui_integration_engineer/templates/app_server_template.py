def _openai_tools_to_anthropic(tools_openai: list[dict]) -> list[dict]:
    """MCP tools are fetched once as OpenAI-style function-calling schemas
    (see _get_chat_tools) since that's the primary LiteLLM/OpenAI-SDK path.
    Bedrock's native tool-use format is structurally the same information,
    just renamed/flattened — no MCP round-trip needed to reshape it."""
    return [
        {
            "name": t["function"]["name"],
            "description": t["function"].get("description", ""),
            "input_schema": t["function"].get("parameters", {"type": "object", "properties": {}}),
        }
        for t in tools_openai
    ]


async def _run_bedrock_chat_stream(system_prompt: str, conversation: list[dict], tools_openai: list[dict],
                                    max_tool_rounds: int = 5):
    """Anthropic-native tool-use loop for the Bedrock fallback path — kept
    separate from the OpenAI-SDK loop below since the two providers' tool-
    calling wire formats are genuinely different shapes.

    An async generator rather than a plain coroutine so the caller can stream
    "tool_call" progress events to the frontend as they happen instead of just
    showing a blank spinner for the whole multi-round turn. Yields
    {"type": "tool_call", ...} as each tool starts, then exactly one
    {"type": "final_text", "text": ...} at the end."""
    client_bedrock = _get_bedrock_chat_client()
    anthropic_tools = _openai_tools_to_anthropic(tools_openai)
    messages: list[dict] = list(conversation)

    for _round in range(max_tool_rounds):
        response = await client_bedrock.messages.create(
            model=BEDROCK_MODEL_ID,
            max_tokens=4096,
            system=system_prompt,
            messages=messages,
            tools=anthropic_tools,
        )

        if response.stop_reason != "tool_use":
            yield {"type": "final_text", "text": "".join(b.text for b in response.content if b.type == "text")}
            return

        tool_use_blocks = [b for b in response.content if b.type == "tool_use"]
        if not tool_use_blocks:
            yield {"type": "final_text", "text": "".join(b.text for b in response.content if b.type == "text")}
            return

        messages.append({"role": "assistant", "content": response.content})
        tool_results = []
        for block in tool_use_blocks:
            print(f"[chat] Bedrock tool call: {block.name}({json.dumps(block.input, default=str)[:200]})", flush=True)
            yield {"type": "tool_call", "tool": block.name, "args": block.input}
            result = await _execute_chat_tool(block.name, block.input)
            tool_results.append({"type": "tool_result", "tool_use_id": block.id, "content": result})
        messages.append({"role": "user", "content": tool_results})

    yield {
        "type": "final_text",
        "text": "".join(b.text for b in response.content if b.type == "text")
        or "I wasn't able to complete the analysis in the allowed steps.",
    }


# --- Database ---
def _get_db() -> sqlite3.Connection:
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA journal_mode=WAL")
    conn.execute("PRAGMA foreign_keys=ON")
    return conn


def _init_db():
    """Initialize database from schema.sql and seed.sql if they exist.

    Supports incremental refinement: if database already has tables, only
    CREATE IF NOT EXISTS and seed NEW tables (those that are empty).
    """
    conn = _get_db()
    schema_file = Path("schema.sql")
    seed_file = Path("seed.sql")

    if schema_file.exists():
        existing_tables = {r[0] for r in conn.execute(
            "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'"
        ).fetchall()}

        if not existing_tables:
            conn.executescript(schema_file.read_text(encoding="utf-8"))
            print(f"[db] Executed schema.sql (new database)")
        else:
            # Incremental: run schema with IF NOT EXISTS to add new tables
            schema_sql = schema_file.read_text(encoding="utf-8")
            # Inject IF NOT EXISTS into CREATE TABLE statements that lack it
            import re as _re
            schema_sql = _re.sub(
                r"CREATE\s+TABLE\s+(?!IF\s+NOT\s+EXISTS)",
                "CREATE TABLE IF NOT EXISTS ",
                schema_sql,
                flags=_re.IGNORECASE,
            )
            try:
                conn.executescript(schema_sql)
                new_tables = {r[0] for r in conn.execute(
                    "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'"
                ).fetchall()} - existing_tables
                if new_tables:
                    print(f"[db] Added new tables: {', '.join(sorted(new_tables))}")
                else:
                    print(f"[db] Schema up to date ({len(existing_tables)} tables)")
            except Exception as e:
                print(f"[db] Schema update warning: {e}")

    if seed_file.exists():
        tables = conn.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'").fetchall()
        # Seed tables that are empty (supports adding data to new tables during refinement)
        empty_tables = set()
        for (table_name,) in tables:
            count = conn.execute(f"SELECT COUNT(*) FROM [{table_name}]").fetchone()[0]
            if count == 0:
                empty_tables.add(table_name)

        if empty_tables:
            # Extract and run INSERT statements for empty tables only
            seed_sql = seed_file.read_text(encoding="utf-8")
            import re as _re
            # Replace literal 'null' in VALUES with empty string to avoid NOT NULL violations
            seed_sql = _re.sub(r",null([,)])", r",''\\1", seed_sql, flags=_re.IGNORECASE)
            seed_sql = _re.sub(r"\(null,", "('',", seed_sql, flags=_re.IGNORECASE)
            # Split on INSERT INTO to process per-table
            statements = _re.split(r"(?=INSERT\s+INTO)", seed_sql, flags=_re.IGNORECASE)
            seeded = []
            for stmt in statements:
                stmt = stmt.strip()
                if not stmt:
                    continue
                # Find target table name
                m = _re.match(r"INSERT\s+INTO\s+[`\"]?(\w+)[`\"]?", stmt, _re.IGNORECASE)
                if m and m.group(1) in empty_tables:
                    try:
                        conn.executescript(stmt)
                        seeded.append(m.group(1))
                    except Exception as e:
                        # Retry with OR IGNORE to skip constraint-violating rows
                        try:
                            stmt_ignore = _re.sub(
                                r"INSERT\s+INTO",
                                "INSERT OR IGNORE INTO",
                                stmt,
                                flags=_re.IGNORECASE,
                            )
                            conn.executescript(stmt_ignore)
                            seeded.append(m.group(1))
                            print(f"[db] Seeded {m.group(1)} with OR IGNORE (some rows skipped)")
                        except Exception as e2:
                            print(f"[db] Seed warning for {m.group(1)}: {e2}")
                elif not m:
                    # Non-INSERT preamble (pragmas, etc.) — run unconditionally
                    try:
                        conn.executescript(stmt)
                    except Exception:
                        pass
            if seeded:
                print(f"[db] Seeded new tables: {', '.join(sorted(set(seeded)))}")
            else:
                print(f"[db] No empty tables to seed")
        else:
            print(f"[db] Skipped seed.sql (all tables have data)")

    _apply_versioned_migrations(conn)
    conn.close()


def _apply_versioned_migrations(conn: sqlite3.Connection):
    """Apply schema_v2.sql/seed_v2.sql (etc.) pairs from a refine's
    incremental DB delta — see CrewOrchestrator._run_data_modeling_refine.
    Unlike v1's schema.sql above (safe to re-run every startup via CREATE
    TABLE IF NOT EXISTS), these can contain ALTER TABLE ADD COLUMN, which
    SQLite errors on if run twice — so each version is tracked in
    _schema_migrations and applied exactly once, ever.
    """
    import re as _re

    conn.execute(
        "CREATE TABLE IF NOT EXISTS _schema_migrations (version INTEGER PRIMARY KEY, applied_at TEXT)"
    )
    conn.commit()
    applied = {r[0] for r in conn.execute("SELECT version FROM _schema_migrations").fetchall()}

    versions = sorted(
        int(m.group(1)) for f in Path(".").glob("schema_v*.sql")
        for m in [_re.match(r"schema_v(\d+)\.sql$", f.name)] if m
    )
    for version in versions:
        if version in applied:
            continue
        schema_file = Path(f"schema_v{version}.sql")
        seed_file = Path(f"seed_v{version}.sql")
        try:
            conn.executescript(schema_file.read_text(encoding="utf-8"))
            if seed_file.exists():
                seed_sql = seed_file.read_text(encoding="utf-8")
                seed_sql = _re.sub(r",null([,)])", r",''\1", seed_sql, flags=_re.IGNORECASE)
                seed_sql = _re.sub(r"\(null,", "('',", seed_sql, flags=_re.IGNORECASE)
                conn.executescript(seed_sql)
            conn.execute(
                "INSERT INTO _schema_migrations (version, applied_at) VALUES (?, datetime('now'))",
                (version,),
            )
            conn.commit()
            print(f"[db] Applied migration v{version} (schema_v{version}.sql" +
                  (f" + seed_v{version}.sql" if seed_file.exists() else "") + ")")
        except Exception as e:
            print(f"[db] Migration v{version} failed, will retry next startup: {e}")


def _get_tables() -> list[str]:
    conn = _get_db()
    rows = conn.execute(
        "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'"
    ).fetchall()
    conn.close()
    return [r["name"] for r in rows]


def _get_table_schema(table: str) -> list[dict]:
    conn = _get_db()
    rows = conn.execute(f"PRAGMA table_info('{table}')").fetchall()
    conn.close()
    return [{"name": r["name"], "type": r["type"], "pk": bool(r["pk"]), "nullable": not r["notnull"]} for r in rows]


def _get_table_count(table: str) -> int:
    conn = _get_db()
    count = conn.execute(f"SELECT COUNT(*) as c FROM [{table}]").fetchone()["c"]
    conn.close()
    return count


