def _parse_filter(filter_str: str) -> tuple[str, list]:
    """Parse 'column:operator:value' into SQL WHERE clause."""
    parts = filter_str.split(":", 2)
    if len(parts) != 3:
        return "", []
    col, op, val = parts
    col_safe = re.sub(r"[^a-zA-Z0-9_]", "", col)
    ops = {"eq": "=", "ne": "!=", "gt": ">", "lt": "<", "gte": ">=", "lte": "<=", "like": "LIKE"}
    if op == "in":
        values = val.split(",")
        placeholders = ",".join("?" * len(values))
        return f"[{col_safe}] IN ({placeholders})", values
    if op not in ops:
        return "", []
    sql_op = ops[op]
    if op == "like":
        val = f"%{val}%"
    return f"[{col_safe}] {sql_op} ?", [val]


@app.get("/api/data/{table}")
async def get_table_data(
    table: str,
    limit: int = Query(100, ge=1, le=1000),
    offset: int = Query(0, ge=0),
    sort: str | None = None,
    order: str = Query("asc", regex="^(asc|desc)$"),
    filter: str | None = None,
):
    tables = _get_tables()
    if table not in tables:
        raise HTTPException(status_code=404, detail=f"Table '{table}' not found")

    conn = _get_db()
    where_clause = ""
    params: list = []

    if filter:
        filters = filter.split(";")
        conditions = []
        for f in filters:
            clause, vals = _parse_filter(f)
            if clause:
                conditions.append(clause)
                params.extend(vals)
        if conditions:
            where_clause = "WHERE " + " AND ".join(conditions)

    count_sql = f"SELECT COUNT(*) as c FROM [{table}] {where_clause}"
    total = conn.execute(count_sql, params).fetchone()["c"]

    sort_clause = ""
    if sort:
        sort_safe = re.sub(r"[^a-zA-Z0-9_]", "", sort)
        sort_clause = f"ORDER BY [{sort_safe}] {order.upper()}"

    query = f"SELECT * FROM [{table}] {where_clause} {sort_clause} LIMIT ? OFFSET ?"
    rows = conn.execute(query, params + [limit, offset]).fetchall()
    conn.close()

    data = [dict(r) for r in rows]
    return {
        "data": data,
        "total": total,
        "limit": limit,
        "offset": offset,
        "hasMore": (offset + limit) < total,
    }


# NOTE: /aggregate must be registered BEFORE /{row_id} — Starlette matches
# routes in registration order, and the literal "aggregate" segment would
# otherwise be captured by {row_id}, failing int-parsing validation before
# ever reaching this handler (confirmed live: GET /api/data/sales/aggregate
# 422'd with "unable to parse 'aggregate' as an integer" until this was
# reordered). Previously masked because nothing called this endpoint over
# HTTP — the old chat-tool code queried the DB directly instead.
@app.get("/api/data/{table}/aggregate")
async def get_table_aggregate(
    table: str,
    groupBy: str | None = None,
    metric: str = Query("count", regex="^(sum|avg|min|max|count)$"),
    column: str | None = None,
    filter: str | None = None,
    limit: int = Query(50, ge=1, le=200),
):
    tables = _get_tables()
    if table not in tables:
        raise HTTPException(status_code=404, detail=f"Table '{table}' not found")

    where_clause = ""
    params: list = []
    if filter:
        filters = filter.split(";")
        conditions = []
        for f in filters:
            clause, vals = _parse_filter(f)
            if clause:
                conditions.append(clause)
                params.extend(vals)
        if conditions:
            where_clause = "WHERE " + " AND ".join(conditions)

    if metric == "count":
        agg_expr = "COUNT(*)"
    else:
        if not column:
            raise HTTPException(status_code=400, detail=f"'column' required for metric '{metric}'")
        col_safe = re.sub(r"[^a-zA-Z0-9_]", "", column)
        agg_expr = f"{metric.upper()}([{col_safe}])"

    conn = _get_db()
    if groupBy:
        group_safe = re.sub(r"[^a-zA-Z0-9_]", "", groupBy)
        query = f"SELECT [{group_safe}] as _group, {agg_expr} as _value FROM [{table}] {where_clause} GROUP BY [{group_safe}] ORDER BY _value DESC LIMIT ?"
        rows = conn.execute(query, params + [limit]).fetchall()
        conn.close()
        return {"data": [{"group": r["_group"], "value": r["_value"]} for r in rows]}
    else:
        query = f"SELECT {agg_expr} as _value FROM [{table}] {where_clause}"
        row = conn.execute(query, params).fetchone()
        conn.close()
        return {"value": row["_value"]}


