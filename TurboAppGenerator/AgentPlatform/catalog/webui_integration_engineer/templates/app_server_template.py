def _build_chat_system_prompt(response_format: str = "auto") -> str:
    """Build a system prompt. Data access happens through tool calls, not the prompt."""
    prompt = (
        "You are an expert data analyst for this application.\n\n"
        "You have access to MCP tools that let you query the live database. "
        "ALWAYS use tools to fetch real data before answering data questions. "
        "Never guess or fabricate numbers — call the appropriate get_ or aggregate_ tool. "
        "If unsure which table/column to use, call get_api_metadata first.\n"
    )
    if response_format == "chart":
        prompt += (
            "\n\nIMPORTANT: Respond with a chart. After fetching data, output ONLY valid JSON: "
            '{"type": "bar"|"line"|"donut"|"scatter", "title": "...", "data": [...], "xKey": "fieldName", "yKeys": ["fieldName1"]}'
        )
    elif response_format == "table":
        prompt += "\n\nIMPORTANT: Respond with tabular output as a JSON array of objects."
    elif response_format == "auto":
        prompt += (
            "\n\nResponse format rules:\n"
            "- Chart: wrap in ```chart\\n{json}\\n``` with {type, title, data, xKey, yKeys}\n"
            "- Map: wrap in ```map\\n{json}\\n``` with {mapType: world|usa, title, data: [{id, value, label}], valueLabel, colorScheme}\n"
            "- Table: wrap in ```table\\n[{...}]\\n```\n"
            "- Otherwise: plain text with markdown\n"
            "- ALWAYS base answers on actual tool call results, not assumptions."
        )
    return prompt


from fastmcp import Client as _MCPClient

_MCP_SELF_URL = f"http://localhost:{API_PORT}/mcp"
_mcp_client: _MCPClient | None = None
_mcp_tools_openai: list[dict] | None = None


async def _get_mcp_client() -> _MCPClient:
    """Lazily connect to this same process's own /mcp mount, reused across
    requests. Lazy (not connected at module-import time or in the startup
    hook) because there's no running event loop until a request handler
    actually runs — matches this codebase's existing precedent of lazy,
    cached discovery on first chat request."""
    global _mcp_client
    if _mcp_client is None or not _mcp_client.is_connected():
        _mcp_client = _MCPClient(_MCP_SELF_URL)
        await _mcp_client.__aenter__()
    return _mcp_client


async def _get_chat_tools() -> list[dict]:
    """Fetch tools from the real MCP server (mounted at /mcp on this same
    process) once, converted to OpenAI function-calling format. MCP tool
    schemas are already JSON-Schema, so this is a straight field mapping."""
    global _mcp_tools_openai
    if _mcp_tools_openai is None:
        client = await _get_mcp_client()
        mcp_tools = await client.list_tools()
        _mcp_tools_openai = [
            {
                "type": "function",
                "function": {
                    "name": t.name,
                    "description": t.description or "",
                    "parameters": t.inputSchema,
                },
            }
            for t in mcp_tools
        ]
    return _mcp_tools_openai


async def _execute_chat_tool(name: str, args: dict) -> str:
    """Execute a tool call via the real MCP server instead of querying the
    local DB directly — the query logic itself now lives in mcp_server.py so
    it's shared with the Java-backend sidecar deployment of this same tool
    server."""
    try:
        client = await _get_mcp_client()
        result = await client.call_tool(name, args)
        data = result.data if hasattr(result, "data") else result
        return data if isinstance(data, str) else json.dumps(data, default=str)
    except Exception as e:
        return json.dumps({"error": f"Tool execution failed: {str(e)}"})


def _parse_llm_response(text: str) -> dict[str, Any]:
    """Parse LLM response for embedded chart/table/map blocks."""
    map_match = re.search(r"```map\s*\n([\s\S]*?)\n```", text)
    if map_match:
        try:
            data = json.loads(map_match.group(1))
            clean = text[:map_match.start()].strip() + "\n\n" + text[map_match.end():].strip()
            return {"response": clean.strip(), "type": "map", "data": data}
        except json.JSONDecodeError:
            pass

    chart_match = re.search(r"```chart\s*\n([\s\S]*?)\n```", text)
    if chart_match:
        try:
            data = json.loads(chart_match.group(1))
            clean = text[:chart_match.start()].strip() + "\n\n" + text[chart_match.end():].strip()
            return {"response": clean.strip(), "type": "chart", "data": data}
        except json.JSONDecodeError:
            pass

    table_match = re.search(r"```table\s*\n([\s\S]*?)\n```", text)
    if table_match:
        try:
            data = json.loads(table_match.group(1))
            clean = text[:table_match.start()].strip() + "\n\n" + text[table_match.end():].strip()
            return {"response": clean.strip(), "type": "table", "data": data}
        except json.JSONDecodeError:
            pass

    try:
        data = json.loads(text)
        if isinstance(data, dict) and "type" in data:
            return {"response": text, "type": "chart", "data": data}
        if isinstance(data, list):
            return {"response": text, "type": "table", "data": data}
    except json.JSONDecodeError:
        pass

    return {"response": text, "type": "text", "data": None}


async def _run_litellm_chat_stream(loop_messages: list[dict], tools: list[dict], max_rounds: int = 5):
    """OpenAI-SDK tool-use loop against LiteLLM. `loop_messages` is mutated in
    place as rounds progress — same as the previous non-streaming version,
    just yielding "tool_call" progress events instead of only returning text."""
    global llm_client
    for _round in range(max_rounds):
        completion = await llm_client.chat.completions.create(
            model=LITELLM_MODEL,
            messages=loop_messages,
            tools=tools,
            temperature=0.3,
        )
        choice = completion.choices[0]

        if choice.finish_reason == "tool_calls" or (choice.message.tool_calls and len(choice.message.tool_calls) > 0):
            loop_messages.append(choice.message)
            for tc in choice.message.tool_calls:
                fn_name = tc.function.name
                fn_args = json.loads(tc.function.arguments) if tc.function.arguments else {}
                print(f"[chat] Tool call: {fn_name}({json.dumps(fn_args)})", flush=True)
                yield {"type": "tool_call", "tool": fn_name, "args": fn_args}
                result = await _execute_chat_tool(fn_name, fn_args)
                loop_messages.append({"role": "tool", "tool_call_id": tc.id, "content": result})
        else:
            yield {"type": "final_text", "text": choice.message.content or ""}
            return

    # Max rounds exhausted — one more plain call for whatever answer we can get
    final = await llm_client.chat.completions.create(
        model=LITELLM_MODEL,
        messages=loop_messages,
        temperature=0.3,
    )
    yield {"type": "final_text", "text": final.choices[0].message.content or ""}


def _sse(event: dict) -> str:
    return f"data: {json.dumps(event, default=str)}\n\n"


async def _stream_chat_events(request: "ChatRequest"):
    """
    Drives the whole /api/chat turn as a stream of SSE events instead of one
    blocking JSON response, so the frontend can show real per-tool-call
    progress instead of a blank spinner for the whole multi-round turn.
    Event types: tool_call, status (provider retry/fallback), final (the
    parse result), error (terminal failure — once streaming has started, a
    real HTTPException can no longer be raised, so failures become events).
    """
    import asyncio
    from openai import AsyncOpenAI
    global llm_client, http_client, _chat_using_fallback

    system_prompt = _build_chat_system_prompt(response_format=request.responseFormat or "auto")
    if request.context:
        system_prompt += f"\n\nAdditional context: {json.dumps(request.context)}"

    recent = request.messages[-20:] if len(request.messages) > 20 else request.messages
    conversation = [{"role": m.role, "content": m.content} for m in recent]
    tools = await _get_chat_tools()
    max_rounds = 5

    # Sticky fallback: LiteLLM already known to be down this session — skip
    # straight to Bedrock instead of wasting more retries against it.
    if _chat_using_fallback:
        try:
            final_text = None
            async for evt in _run_bedrock_chat_stream(system_prompt, conversation, tools, max_rounds):
                if evt["type"] == "final_text":
                    final_text = evt["text"]
                else:
                    yield _sse(evt)
            yield _sse({"type": "final", "result": _parse_llm_response(final_text or "")})
        except Exception as e:
            yield _sse({"type": "error", "detail": f"Bedrock call failed: {e}"})
        return

    messages = [{"role": "system", "content": system_prompt}] + conversation

    last_err = None
    for _attempt in range(3):
        try:
            loop_messages = list(messages)
            final_text = None
            async for evt in _run_litellm_chat_stream(loop_messages, tools, max_rounds):
                if evt["type"] == "final_text":
                    final_text = evt["text"]
                else:
                    yield _sse(evt)
            yield _sse({"type": "final", "result": _parse_llm_response(final_text or "")})
            return
        except Exception as attempt_err:
            last_err = attempt_err
            print(f"[chat] attempt {_attempt+1} failed: {type(attempt_err).__name__}: {attempt_err}", flush=True)
            if _attempt < 2:
                yield _sse({"type": "status", "message": "Connection hiccup — retrying..."})
                try:
                    await http_client.aclose()
                except Exception:
                    pass
                http_client = _make_http_client()
                llm_client = AsyncOpenAI(
                    api_key=LITELLM_API_KEY,
                    base_url=LITELLM_API_BASE.rstrip("/") + "/v1",
                    http_client=http_client,
                    timeout=LITELLM_TIMEOUT,
                )
                await asyncio.sleep(2 * (_attempt + 1))

    # LiteLLM exhausted all retries — fall back to Bedrock rather than
    # failing the request outright. Sticky: every subsequent /api/chat call
    # in this process goes straight to Bedrock (see the check above).
    print(
        f"\n{'='*60}\n"
        f"[CHAT FALLBACK] LiteLLM unavailable after 3 attempts.\n"
        f"                Switching to AWS Bedrock ({BEDROCK_MODEL_ID}).\n"
        f"                Last error: {last_err}\n"
        f"{'='*60}\n",
        flush=True,
    )
    yield _sse({"type": "status", "message": "Primary AI service unavailable — switching to backup..."})
    _chat_using_fallback = True
    try:
        final_text = None
        async for evt in _run_bedrock_chat_stream(system_prompt, conversation, tools, max_rounds):
            if evt["type"] == "final_text":
                final_text = evt["text"]
            else:
                yield _sse(evt)
        yield _sse({"type": "final", "result": _parse_llm_response(final_text or "")})
    except Exception as bedrock_err:
        err_msg = f"Both LiteLLM and Bedrock failed.\n  LiteLLM error: {last_err}\n  Bedrock error: {bedrock_err}"
        yield _sse({"type": "error", "detail": err_msg})


