# Combined lifespan, not just lifespan=mcp_asgi_app.lifespan directly: this file
# used to run its startup logic (_init_db, _build_metadata) via the older
# @app.on_event("startup") decorator. Passing an explicit `lifespan=` to
# FastAPI() alongside that decorator does NOT reliably run both — verified by
# testing: the app started and /mcp worked fine, but _init_db() silently never
# ran (every table came back empty). Wrapping the original startup logic
# inside one explicit async-context-manager lifespan — which also enters the
# MCP sub-app's own lifespan (required for its session manager to start; a
# bare app.mount() without this produces a mount that accepts connections but
# terminates every session) — is unambiguous and doesn't depend on how a given
# FastAPI version reconciles the two older/newer mechanisms.
from contextlib import asynccontextmanager as _asynccontextmanager


@_asynccontextmanager
async def _lifespan(_app: FastAPI):
    async with mcp_asgi_app.lifespan(_app):
        _init_db()
        _build_metadata()
        tables = _get_tables()
        print(f"\n  TurboUI App Server running on port {API_PORT}")
        print(f"  Database: {DB_PATH} ({len(tables)} tables)")
        print(f"  Endpoints:")
        for meta in _api_metadata:
            print(f"    GET /api/data/{meta['table']}  ({meta['rowCount']} rows)")
        print(f"    GET  /api/metadata        — API catalog")
        print(f"    POST /api/chat            — AI data chat")
        print(f"    GET  /mcp                 — MCP server (tools for /api/chat)")
        print(f"    GET  /health              — Health check\n")
        yield


